#!/bin/bash
set -uo pipefail
source "$HM_LIB"
sha256_stdin() { "$HM_PYTHON" -c 'import sys,hashlib; print(hashlib.sha256(sys.stdin.buffer.read()).hexdigest())'; }

CHART="$SANDBOX/ledger-db"
[ -f "$CHART/Chart.yaml" ] || hm_fail "ledger-db/Chart.yaml is missing from the workspace"
VNS="helmissions-verify-$RANDOM"
cleanup() {
  helm uninstall hm-verify -n "$VNS" >/dev/null 2>&1 || true
  kubectl delete namespace "$VNS" --wait=false >/dev/null 2>&1 || true
  rm -rf "$HM_TMP"
}
trap cleanup EXIT
pw() { kubectl get secret hm-verify-credentials -n "$VNS" -o jsonpath='{.data.password}' 2>/dev/null; }

hm_info "Proving the chart keeps its password across upgrades (throwaway release in $VNS)..."
helm lint "$CHART" >"$HM_TMP/lint.txt" 2>&1 || hm_fail "helm lint reports errors" "$HM_TMP/lint.txt"
kubectl create namespace "$VNS" >/dev/null 2>&1 || hm_fail "could not create the verification namespace"
helm install hm-verify "$CHART" -n "$VNS" >"$HM_TMP/v.txt" 2>&1 || hm_fail "A fresh install of the chart fails" "$HM_TMP/v.txt"
a="$(pw)"; [ -n "$a" ] || hm_fail "A fresh install does not create a password Secret"
helm upgrade hm-verify "$CHART" -n "$VNS" >"$HM_TMP/v.txt" 2>&1 || hm_fail "An upgrade of the chart fails" "$HM_TMP/v.txt"
b="$(pw)"
helm upgrade hm-verify "$CHART" -n "$VNS" --set replicaCount=2 >"$HM_TMP/v.txt" 2>&1 || hm_fail "A second upgrade of the chart fails" "$HM_TMP/v.txt"
c="$(pw)"
[ "$a" = "$b" ] && [ "$b" = "$c" ] || hm_fail "The generated password changes on helm upgrade (install, upgrade and upgrade gave different values)"
[ "$(echo "$a" | base64 -d | wc -c | tr -d ' ')" -ge 8 ] || hm_fail "The generated password is too short to be real"
hm_ok "A new install keeps its password through two upgrades"

hm_info "Checking the real release..."
hm_require_deployed ledgerdb
rev="$(hm_release_revision ledgerdb)"
[ "${rev:-0}" -ge 3 ] || hm_fail "Release ledgerdb is still at revision ${rev:-?} - the fixed chart was never deployed"
want="$(kubectl get configmap registered-credentials -n "$NS" -o jsonpath='{.data.fingerprint}' 2>/dev/null)"
[ -n "$want" ] || hm_fail "The ConfigMap registered-credentials is missing"
live="$(kubectl get secret ledgerdb-credentials -n "$NS" -o jsonpath='{.data.password}' | base64 -d | sha256_stdin)"
[ "$live" = "$want" ] || hm_fail "The password in Secret ledgerdb-credentials is not the one registered with billing - it was regenerated by an upgrade"
m="$(hm_manifest_json ledgerdb | jq -r '[.[] | select(.kind=="Secret") | .data.password] | first // empty' | base64 -d 2>/dev/null | sha256_stdin)"
[ "$m" = "$want" ] || hm_fail "The release manifest's Secret disagrees with the registered password"
hm_wait_rollout deployment/ledgerdb "$NS" 90s

hm_pass "ledgerdb keeps its registered password across upgrades."
